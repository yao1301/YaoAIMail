import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { WorkspaceStateBoundary, useWorkspacePrepare, useWorkspaceState, getWorkspaceScope, hasTransferredWork } from '@/lib/workspaceState';
import { detachWorkspaceTab, disposeWorkspaceBridges, connectWorkspace } from '@/lib/workspaceWindows';
