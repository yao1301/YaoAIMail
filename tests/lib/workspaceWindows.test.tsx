const h = vi.hoisted(() => ({ invoke: vi.fn(), listeners: new Map<string, (event: any) => void>(), resume: vi.fn() }));
vi.mock('@tauri-apps/api/core', () => ({ invoke: h.invoke }));
vi.mock('@tauri-apps/api/event', () => ({ listen: vi.fn(async (name: string, callback: any) => { h.listeners.set(name, callback); return () => h.listeners.delete(name); }) }));
const feature = (view: NavTab['view']): NavTab => ({ key: `feature:${view}`, view, kind: 'feature', label: view });
function Content() { useWorkspaceState('fixture:text', 'unsaved-input'); useWorkspacePrepare(async () => h.resume); return null; }
beforeEach(() => {
  h.invoke.mockReset().mockResolvedValue(undefined); h.resume.mockReset(); h.listeners.clear();
  useUIStore.setState({ activeView: 'leadFinder', navTabs: [], aiBgTask: null });
  useMailStore.setState({ activeAccountId: 'account-fixture', activeFolderId: 'folder-fixture' });
  useBackgroundTasksStore.setState({ tasks: {} });
  useComposeStore.setState({ tabs: [], tabsById: {}, activeTabId: null, composeMode: null });
});
afterEach(() => { disposeWorkspaceBridges(); cleanup(); });
it('retains the source until the final result IPC finishes, even after its busy flag clears',async()=>{
  const scope=new WorkspaceStateScope();
  const bridge=await connectWorkspace('fixture-transport',scope,false,[]);
  await bridge.enable();
  let complete!:()=>void;
  h.invoke.mockImplementation((command:string)=>command==='update_workspace_window'?new Promise<void>(resolve=>{complete=resolve;}):Promise.resolve());
  const delivery=bridge.send('@ai',{body:'fixture final result'});
  await vi.waitFor(()=>expect(complete).toBeTypeOf('function'));
  expect(hasTransferredWork()).toBe(true);
  complete();await delivery;
  expect(hasTransferredWork()).toBe(false);
});
it.each(['leadFinder','companyResearch','settings','aiWriting','foreignTools','addressBook','customerProfile','starred','search','kanban'] as const)('hands off %s only after native readiness', async view => {
  let finish!: () => void; h.invoke.mockImplementation((command: string) => command === 'open_workspace_window' ? new Promise<void>(resolve => { finish = resolve; }) : Promise.resolve());
  const tab = feature(view); useUIStore.setState({ activeView: view, navTabs: [tab] });
  render(<WorkspaceStateBoundary id={tab.key}><Content/></WorkspaceStateBoundary>);
  const moving = detachWorkspaceTab(tab);
  await vi.waitFor(() => expect(h.invoke).toHaveBeenCalledWith('open_workspace_window', expect.anything()));
  expect(useUIStore.getState().navTabs).toContainEqual(tab);
  const args = h.invoke.mock.calls.find(call => call[0] === 'open_workspace_window')![1];
  const payload = decodeWorkspaceValue(JSON.parse(args.payload).content) as any;
  expect(payload.state['fixture:text']).toBe('unsaved-input'); expect(payload.mail.activeAccountId).toBe('account-fixture');
  await act(async () => { finish(); await moving; });
  expect(useUIStore.getState().navTabs).not.toContainEqual(tab);
});
it('resumes the original editor and retains the tab if handoff fails', async () => {
  const tab = feature('settings'); useUIStore.setState({ navTabs: [tab] });
  render(<WorkspaceStateBoundary id={tab.key}><Content/></WorkspaceStateBoundary>);
  h.invoke.mockImplementation((command: string) => command === 'open_workspace_window' ? Promise.reject(new Error('fixture failure')) : Promise.resolve());
  await expect(detachWorkspaceTab(tab)).rejects.toThrow('fixture failure');
  expect(useUIStore.getState().navTabs).toContainEqual(tab); expect(h.resume).toHaveBeenCalledOnce();
  expect(getWorkspaceScope(tab.key)?.element?.hasAttribute('inert')).toBe(false);
});
it('restores the original tab immediately when the loading window is closed', async () => {
  const tab = feature('companyResearch'); useUIStore.setState({ navTabs: [tab] });
  render(<WorkspaceStateBoundary id={tab.key}><Content /></WorkspaceStateBoundary>);
  h.invoke.mockImplementation((command: string) => command === 'open_workspace_window' ? new Promise(() => {}) : Promise.resolve());
  const moving = detachWorkspaceTab(tab);
  const rejected = expect(moving).rejects.toThrow('独立窗口已关闭');
  await vi.waitFor(() => expect(h.invoke).toHaveBeenCalledWith('open_workspace_window', expect.anything()));
  const args = h.invoke.mock.calls.find(call => call[0] === 'open_workspace_window')![1];
  h.listeners.get('workspace:closed')!({ payload: { token: args.token } });
  await rejected;
  expect(useUIStore.getState().navTabs).toContainEqual(tab);
  expect(h.resume).toHaveBeenCalledOnce();
  expect(getWorkspaceScope(tab.key)?.element?.hasAttribute('inert')).toBe(false);
});
it('buffers a model response arriving during draft handoff and delivers to the original draft ID', async () => {
  useComposeStore.getState().openCompose('new', null, { accountId: 'account-fixture', subject: 'Fixture draft' });
  const tab = useComposeStore.getState().tabs[0];
  render(<WorkspaceStateBoundary id={`compose:${tab.id}`}><Content/></WorkspaceStateBoundary>);
  let finish!: () => void; h.invoke.mockImplementation((command: string) => command === 'open_workspace_window' ? new Promise<void>(resolve => { finish = resolve; }) : Promise.resolve());
  const moving = detachWorkspaceTab(tab);
  await vi.waitFor(() => expect(h.invoke).toHaveBeenCalledWith('open_workspace_window', expect.anything()));
  expect(deliverAiDraft({ tabId: tab.id, accountId: 'account-fixture' }, { body: 'late fixture body' })).toBe('queued');
  expect(useComposeStore.getState().tabsById[tab.id].pendingAiBody).toBeNull();
  await act(async () => { finish(); await moving; });
  const patch = h.invoke.mock.calls.find(call => call[0] === 'update_workspace_window' && call[1].key === '@ai')![1];
  const decoded = decodeWorkspaceValue(JSON.parse(patch.value)) as any;
  expect(decoded.target.tabId).toBe(tab.id); expect(decoded.draft.body).toBe('late fixture body');
  expect(useComposeStore.getState().tabsById[tab.id]).toBeUndefined();
  h.listeners.get('workspace:closed')!({ payload: { token: patch.token } });
});
