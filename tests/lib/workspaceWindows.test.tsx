it('hands off a search completion during window loading once, retaining unrelated tasks', async () => {
  const tab = feature('leadFinder'); useUIStore.setState({ navTabs: [tab] });
  render(<WorkspaceStateBoundary id={tab.key}><Content/></WorkspaceStateBoundary>);
  const task = { id: 'leadFinder', label: 'fixture search', status: 'running' as const, startedAt: 1 };
  const unrelated = { ...task, id: 'companyResearch' };
  useBackgroundTasksStore.setState({ tasks: { leadFinder: task, companyResearch: unrelated } });
  let finish!: () => void; h.invoke.mockImplementation((command: string) => command === 'open_workspace_window' ? new Promise<void>(resolve => { finish = resolve; }) : Promise.resolve());
  const moving = detachWorkspaceTab(tab);
  await vi.waitFor(() => expect(h.invoke).toHaveBeenCalledWith('open_workspace_window', expect.anything()));
  expect(hasTransferredWork()).toBe(true);
  act(() => useBackgroundTasksStore.setState({ tasks: { leadFinder: { ...task, status: 'success', result: { items: ['fixture-result'] } }, companyResearch: unrelated } }));
  expect(getWorkspaceScope(tab.key)?.transferring).toBe(true);
  expect(useBackgroundTasksStore.getState().tasks.leadFinder?.status).toBe('success');
  await act(async () => { finish(); await moving; });
  const patches = h.invoke.mock.calls.filter(call => call[0] === 'update_workspace_window' && call[1].key === '@tasks');
  expect(patches).toHaveLength(1);
  expect((decodeWorkspaceValue(JSON.parse(patches[0][1].value)) as any).leadFinder.result.items).toEqual(['fixture-result']);
  expect(useBackgroundTasksStore.getState().tasks.leadFinder).toBeUndefined();
  expect(useBackgroundTasksStore.getState().tasks.companyResearch).toBe(unrelated);
  expect(hasTransferredWork()).toBe(false);
});
